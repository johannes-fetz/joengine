#!/bin/sh
# Builds the sound driver of the 68000 (driver.c) and writes ../audio_driver_68k.h (the binary as a C array, included
# by audio.c). Linux: sudo apt install gcc-m68k-linux-gnu
set -e
cd "$(dirname "$0")"
CC=${CC:-m68k-linux-gnu-gcc}
OBJCOPY=${OBJCOPY:-m68k-linux-gnu-objcopy}
$CC -m68000 -Os -ffreestanding -fno-builtin -nostdlib -fno-pic -fomit-frame-pointer -W -Wall -Wextra -Werror \
    --param=min-pagesize=0 \
    -Wl,--build-id=none -Wl,--no-warn-rwx-segments -Wl,-z,noexecstack -T driver.ld -o driver.elf crt0.S driver.c -lgcc
$OBJCOPY -O binary driver.elf driver.bin
python3 - <<'PY'
data = open('driver.bin', 'rb').read()
if len(data) & 1:
    data += b'\x00'   # (copied by 16 bits words)
lines = ['/* Generated by jo_engine/sound_driver/build.sh from sound_driver/driver.c: do not edit */', '',
         '/** @brief The sound driver of the 68000 (%d bytes, at the address 0 of the sound RAM) */' % len(data),
         'static const unsigned char jo_audio_driver_68k[%d] =' % len(data), '{']
for k in range(0, len(data), 16):
    lines.append('    ' + ', '.join('0x%02X' % b for b in data[k:k + 16]) + ',')
lines += ['};', '']
open('../audio_driver_68k.h', 'w', newline='\r\n').write('\n'.join(lines))
print('audio_driver_68k.h: %d bytes' % len(data))
PY
rm -f driver.elf driver.bin
